def validate_codex_rules_available(root: Path, errors: list[str], quick: bool) -> None:
    rules = root / ".codex" / "rules" / "default.rules"
    text = read(rules)
    for required in ["prefix_rule(", "match = [", "not_match = [", "decision = \"forbidden\"", "decision = \"prompt\""]:
        if required not in text:
            fail(errors, f"Codex rules file missing expected syntax: {required}")
    if quick:
        return
    codex = shutil.which("codex")
    if not codex:
        print("codex CLI unavailable; static .rules checks used as documented fallback")
        return
    result = subprocess.run(
        [codex, "execpolicy", "check", "--rules", str(rules), "--", "git", "status"],
        cwd=root,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=False,
    )
    if result.returncode != 0:
        fail(errors, f"codex execpolicy check failed: {result.stderr.strip() or result.stdout.strip()}")


def validate(quick: bool = False) -> int:
    root = repo_root()
    errors: list[str] = []
    validate_required_files(root, errors)
    validate_root_links(root, errors)
    validate_skills(root, errors)
    validate_json_toml(root, errors)
    validate_manifest_paths(root, errors)
    validate_hooks(root, errors)
    validate_delivery_templates(root, errors)
    validate_team_ready_governance(root, errors)
    validate_code_quality_profiles(root, errors)
    validate_prompt_catalog(root, errors)
    validate_agent_adapter_strategy(root, errors)
    validate_delivery_artifact_generator(root, errors)
    validate_repository_intelligence(root, errors, quick)
    validate_secret_like_values(root, errors)
    validate_instruction_budgets(root, errors)
    validate_codex_rules_available(root, errors, quick)

    if errors:
        for error in errors:
            print(f"ERROR: {error}", file=sys.stderr)
        return 1
    print("agent configuration validation passed")
    return 0


