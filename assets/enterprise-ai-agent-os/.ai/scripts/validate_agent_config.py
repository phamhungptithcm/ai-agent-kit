def validate_hooks(root: Path, errors: list[str]) -> None:
    hooks_file = root / ".codex" / "hooks.json"
    try:
        hooks = json.loads(read(hooks_file))
    except Exception:
        return
    commands: list[str] = []
    for groups in hooks.get("hooks", {}).values():
        for group in groups:
            for hook in group.get("hooks", []):
                command = hook.get("command", "")
                command_windows = hook.get("commandWindows", "")
                if command:
                    commands.append(command)
                if command_windows:
                    commands.append(command_windows)
    for command in commands:
        lowered = command.lower()
        if any(term in lowered for term in ["curl ", "wget ", "invoke-webrequest", "http://", "https://", "iex "]):
            fail(errors, f"hook command appears to use network or download execution: {command}")
        match = re.search(r"(\.ai[\\/ ]scripts[\\/][A-Za-z0-9_.-]+\.(?:py|mjs))", command)
        if match:
            rel = match.group(1).replace(" ", "/").replace("\\", "/")
            if not (root / rel).exists():
                fail(errors, f"hook references missing script: {rel}")
    joined = "\n".join(commands)
    if "bootstrap-repository-intelligence" not in joined and "check-repository-intelligence" not in joined:
        fail(errors, "session hooks do not invoke the Repository Intelligence Gate")
    if "validate_implementation_approval.py --hook" not in joined:
        fail(errors, "pre-tool hooks do not enforce tracked implementation approval")
    if "enforce_command_policy.py --hook" not in joined:
        fail(errors, "pre-tool hooks do not enforce command policy")
    if "governed_action_gateway.mjs" not in joined:
        fail(errors, "pre-tool hooks do not invoke the universal action gateway")


