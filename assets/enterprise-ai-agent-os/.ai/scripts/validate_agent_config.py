def validate_delivery_artifact_generator(root: Path, errors: list[str]) -> None:
    with tempfile.TemporaryDirectory() as tmp:
        out_dir = Path(tmp) / "artifacts"
        result = subprocess.run(
            [
                sys.executable,
                str(root / ".ai" / "scripts" / "generate_delivery_artifacts.py"),
                "--jira-key",
                "DEMO-000",
                "--title",
                "Validation Artifact",
                "--output-dir",
                str(out_dir),
                "--json",
            ],
            cwd=root,
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            check=False,
        )
        if result.returncode != 0:
            fail(errors, f"delivery artifact generator failed: {result.stderr.strip() or result.stdout.strip()}")
            return
        try:
            payload = json.loads(result.stdout)
        except json.JSONDecodeError as exc:
            fail(errors, f"delivery artifact generator did not emit JSON: {exc}")
            return
        required_keys = {"summary", "pptx", "xlsx", "screenshot_placeholders"}
        if set(payload) != required_keys:
            fail(errors, f"delivery artifact generator emitted wrong keys: {sorted(payload)}")
            return
        for label, artifact_path in payload.items():
            path = Path(artifact_path)
            if not path.exists() or path.stat().st_size == 0:
                fail(errors, f"generated {label} artifact missing or empty: {path}")

        summary_text = Path(payload["summary"]).read_text(encoding="utf-8")
        if "DEMO-000" not in summary_text or "Validation Artifact" not in summary_text or "SS-01" not in summary_text:
            fail(errors, "generated Jira summary missing key, title, or screenshot placeholder")

        with zipfile.ZipFile(payload["pptx"]) as deck:
            names = set(deck.namelist())
            for required in ["ppt/presentation.xml", "ppt/slides/slide1.xml", "ppt/slides/slide6.xml"]:
                if required not in names:
                    fail(errors, f"generated PPTX missing {required}")
            slide_text = deck.read("ppt/slides/slide1.xml").decode("utf-8", errors="replace")
            if "DEMO-000" not in slide_text or "Validation Artifact" not in slide_text:
                fail(errors, "generated PPTX missing Jira key or title")

        with zipfile.ZipFile(payload["xlsx"]) as book:
            names = set(book.namelist())
            for required in ["xl/workbook.xml", "xl/worksheets/sheet1.xml", "xl/worksheets/sheet5.xml"]:
                if required not in names:
                    fail(errors, f"generated XLSX missing {required}")
            sheet_text = book.read("xl/worksheets/sheet1.xml").decode("utf-8", errors="replace")
            if "DEMO-000" not in sheet_text or "Validation Artifact" not in sheet_text:
                fail(errors, "generated XLSX missing Jira key or title")


